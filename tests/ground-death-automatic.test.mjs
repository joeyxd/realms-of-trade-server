import test from 'node:test';
import assert from 'node:assert/strict';
import { fixture, joinPlayer, placeInCala, injectStep, turn, OWNER, OTHER, composedStore } from './helpers/ground-death-host.mjs';
import { hurtPlayer } from '../src/sim/systems/combat.js';
import { DROPS } from '../src/data/loot.js';

const lethal = (host, victim, killer) => {
  const w = host.server.world;
  w.ecs.hp[victim.entity] = 1;
  return hurtPlayer(w, victim.entity, 9999, { x: w.ecs.x[victim.entity], z: w.ecs.z[victim.entity],
    kind: 'melee', seq: 31, by: killer?.entity ?? 0, pierce: true, noInv: true, knock: 0 });
};

async function finishDeath(host) {
  for (let i = 0; i < 20 && host.combatDeaths.pending; i++) {
    await host.groundAuthority.settle();
    if (host.combatDeaths.pending) host.server.step();
  }
  assert.equal(host.combatDeaths.pending, false);
}

async function stepUntil(host, done, message) {
  for (let i = 0; i < 80 && !done(); i++) {
    await host.groundAuthority.settle();
    if (!done() && !host.server.step()) await host.groundAuthority.settle();
    await turn();
  }
  assert.ok(done(), message);
}

async function currentRows(f) {
  return composedStore(f.db).listCurrentDeathDrops(f.world);
}

test('automatic ordinary pickup commits and applies once at the cadence selector', async t => {
  const f = await fixture(t, { pearlCount: 0 }), host = f.host;
  try {
    const victim = await joinPlayer(host), killer = await joinPlayer(host, 'other');
    placeInCala(host, victim, killer);
    injectStep(host, () => lethal(host, victim, killer));
    assert.equal(host.server.step(), true, 'fatality is generated by an actual server tick');
    await finishDeath(host);
    await host.profiles.flush();

    const rows = await currentRows(f), item = rows.find(row => row.kind === 'item');
    assert.ok(item, 'death receipt created ordinary item rows');
    const w = host.server.world, profile = w.profiles.get(killer.entity);
    const before = structuredClone(profile), source = [...w.drops.values()].find(drop =>
      drop.operationId === item.operationId && drop.ordinal === item.ordinal);
    assert.ok(source, 'the durable ordinary source is installed in the local world');
    w.ecs.x[killer.entity] = source.x; w.ecs.z[killer.entity] = source.z;
    assert.ok(Math.hypot(w.ecs.x[killer.entity] - source.x, w.ecs.z[killer.entity] - source.z) <= DROPS.pickR);
    const localAvailable = source.pickAt;
    const cadenceTick = localAvailable + ((3 - localAvailable % 3) % 3);
    w.tick = cadenceTick;
    assert.ok(w.tick % 3 === 0, 'the selector cadence is every third world tick');
    assert.ok(w.tick >= source.pickAt && w.tick <= source.t,
      'the automatic selector runs inside the source availability window');

    await stepUntil(host, () => !w.drops.has(source.id), 'automatic selector should consume the nearby item');
    const stored = await composedStore(f.db).loadDeathDrop(item.operationId, item.ordinal);
    assert.equal(stored.state, 'picked');
    assert.equal(stored.holder, OTHER);
    assert.equal(profile.stats.items, before.stats.items + 1);
    assert.equal(profile.bag.length, before.bag.length + 1);
    assert.equal(profile.uid, before.uid + 1);
    assert.equal(host.groundAuthority.status().failed, false);
    assert.equal(host.groundDeaths.status().failed, false);
    assert.equal(host.groundPearls.status().failed, false);
    await host.profiles.flush();
    const persisted = await f.db.store.loadProfile(OTHER);
    assert.equal(persisted.data.stats.items, before.stats.items + 1);
    assert.equal(persisted.data.bag.length, before.bag.length + 1);
  } finally { await host.close().catch(() => {}); }
});

test('automatic expiry transitions every ordinary row after its durable deadline without profile changes', async t => {
  const f = await fixture(t, { pearlCount: 0 }), host = f.host;
  try {
    const victim = await joinPlayer(host), killer = await joinPlayer(host, 'other');
    placeInCala(host, victim, killer);
    injectStep(host, () => lethal(host, victim, killer));
    assert.equal(host.server.step(), true, 'fatality is generated by an actual server tick');
    await finishDeath(host);
    await host.profiles.flush();

    const rows = await currentRows(f);
    assert.ok(rows.length > 0);
    const w = host.server.world, profile = w.profiles.get(killer.entity), before = structuredClone(profile);
    const localDrops = [...w.drops.values()].filter(drop => drop.kind === 'item' || drop.kind === 'potion');
    assert.equal(localDrops.length, rows.length);
    for (const player of [victim, killer]) { w.ecs.x[player.entity] += 10000; w.ecs.z[player.entity] += 10000; }

    const anchor = localDrops[0].groundClock.anchor;
    const lastDurableExpiry = Math.max(...localDrops.map(drop => drop.groundClock.ground.expiresAt));
    w.tick = anchor.localTick + (lastDurableExpiry - anchor.durableTick) + 1;
    assert.ok(localDrops.every(drop => w.tick > drop.t), 'the projected local tick is strictly past each deadline');

    const sourceIds = new Set(localDrops.map(drop => drop.id));
    await stepUntil(host, () => [...sourceIds].every(id => !w.drops.has(id)),
      'automatic expiry selector should remove each overdue ordinary source');
    for (const row of rows) {
      const stored = await composedStore(f.db).loadDeathDrop(row.operationId, row.ordinal);
      assert.equal(stored.state, 'expired');
      assert.equal(stored.holder, null);
    }
    assert.deepEqual(profile, before, 'expiration never grants an item or potion');
    assert.equal(host.groundAuthority.status().failed, false);
    assert.equal(host.groundDeaths.status().failed, false);
    assert.equal(host.groundPearls.status().failed, false);
  } finally { await host.close().catch(() => {}); }
});
