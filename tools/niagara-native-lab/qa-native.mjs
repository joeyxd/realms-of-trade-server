import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import { fileURLToPath, pathToFileURL } from 'node:url';
if (!process.argv[2]) throw new Error('Pass local Playwright index.mjs path');
const { chromium } = await import(pathToFileURL(process.argv[2]).href);
const out = new URL('../../.scratch/native-birth/', import.meta.url);
await fs.mkdir(out, { recursive: true });
const browser = await chromium.launch({ headless: true, channel: 'chrome' });
try {
  const page = await browser.newPage({ viewport: { width: 1280, height: 1250 } });
  const errors = [], requests = [], checks = [];
  page.on('pageerror', e => errors.push(String(e)));
  page.on('console', m => { if (m.type() === 'error') errors.push(m.text()); });
  page.on('request', r => requests.push({ url: r.url(), method: r.method() }));
  await page.goto('http://127.0.0.1:5197/tools/niagara-native-lab/index.html?run=reference11&mode=native');
  await page.waitForFunction(() => window.pilot?.ready || window.pilot?.errors.length);
  assert.ok(await page.evaluate(() => pilot.ready));
  assert.equal(await page.evaluate(() => pilot.count), 22);
  assert.ok(!requests.some(r => r.url.includes('/particles/step_') || r.url.includes('update-fixture.json')));
  checks.push('native starts with source preset; no particle states or births fetched');
  const original = await page.evaluate(() => pilot.particleSnapshot);
  await page.locator('#tone').selectOption('aces'); await page.locator('#tone').dispatchEvent('input');
  await page.locator('#linear-reference').check();
  const saveCanvas = async name => fs.writeFile(new URL(`${name}.png`, out),
    Buffer.from(await page.locator('#preview').evaluate(c => c.toDataURL().split(',')[1]), 'base64'));
  for (const camera of ['front', 'oblique', 'side']) {
    await page.evaluate(v => pilot.setCamera(v), camera);
    await page.screenshot({ path: fileURLToPath(new URL(`native-${camera}.png`, out)), fullPage: true });
    await saveCanvas(`native-canvas-${camera}`);
  }
  await page.locator('#linear-reference').uncheck();
  await page.locator('#seed').fill('42'); await page.locator('#seed').dispatchEvent('input');
  const variant = await page.evaluate(() => pilot.particleSnapshot);
  assert.equal(await page.evaluate(() => pilot.count), 22);
  assert.notDeepEqual(variant.emitters[1], original.emitters[1]);
  await page.evaluate(() => { pilot.seek(0); pilot.seek(120); });
  assert.deepEqual(await page.evaluate(() => pilot.particleSnapshot), variant);
  await page.screenshot({ path: fileURLToPath(new URL('native-seed42.png', out)), fullPage: true });
  await page.locator('#reset-update').click();
  assert.deepEqual(await page.evaluate(() => pilot.particleSnapshot), original);
  checks.push('seed changes appearance repeatably; reset restores exact default snapshot');
  await page.evaluate(() => pilot.seek(420));
  assert.equal(await page.evaluate(() => pilot.count), 23);
  assert.ok(await page.evaluate(() => pilot.particleSnapshot.emitters[1].particles.at(-1).uniqueId > 50));
  await page.screenshot({ path: fileURLToPath(new URL('native-continuous.png', out)), fullPage: true });
  checks.push('new source-only births at 7 s beyond recorded 4 s window');
  await page.locator('#stopAt').fill('1'); await page.locator('#stopAt').dispatchEvent('input');
  await page.evaluate(() => pilot.seek(240)); assert.equal(await page.evaluate(() => pilot.count), 0);
  await page.locator('#reset-update').click(); await page.evaluate(() => pilot.seek(120));
  await page.locator('#smokeSpeed').fill('2'); await page.locator('#smokeSpeed').dispatchEvent('input');
  const fast = await page.evaluate(() => pilot.particleSnapshot);
  assert.deepEqual(fast.emitters[0], original.emitters[0]);
  assert.ok(fast.emitters[1].particles[0].position[2] > original.emitters[1].particles[0].position[2]);
  await page.locator('#smokeLife').fill('4'); await page.locator('#smokeLife').dispatchEvent('input');
  await page.locator('#stopAt').fill('1'); await page.locator('#stopAt').dispatchEvent('input');
  await page.evaluate(() => pilot.seek(240)); assert.ok(await page.evaluate(() => pilot.count > 0));
  await page.evaluate(() => pilot.seek(360)); assert.equal(await page.evaluate(() => pilot.count), 0);
  await page.locator('#reset-update').click(); await page.evaluate(() => pilot.seek(120));
  checks.push('stop drains; speed preserves flame; long life delays death; backward seek resets');
  await page.locator('#flame').uncheck(); assert.equal(await page.evaluate(() => pilot.count), 19);
  await page.locator('#smoke').uncheck(); assert.equal(await page.evaluate(() => pilot.count), 0);
  await page.locator('#flame').check(); await page.locator('#smoke').check();
  const box = await page.locator('#preview').boundingBox();
  await page.mouse.move(box.x+100, box.y+100); await page.mouse.down();
  await page.mouse.move(box.x+160, box.y+140); await page.mouse.up();
  assert.ok(await page.evaluate(() => pilot.freeCamera));
  await page.evaluate(() => pilot.setCamera('front'));
  await page.locator('#play').click(); await page.waitForTimeout(350); await page.locator('#play').click();
  assert.ok(await page.evaluate(() => pilot.frame > 120));
  await page.evaluate(() => pilot.seek(120));
  checks.push('layers, camera orbit and playback operate on native particles');
  await page.setViewportSize({ width: 390, height: 844 });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  assert.equal(await page.locator('#seed').inputValue(), '6371');
  await page.screenshot({ path: fileURLToPath(new URL('native-mobile.png', out)), fullPage: true });
  checks.push('all controls fit 390px; physical mobile performance not measured');
  const nativeOnlyRequests = [...requests];
  await page.setViewportSize({ width: 1280, height: 1250 });
  await page.locator('#mode').selectOption('observed'); await page.waitForFunction(() => pilot.mode === 'observed');
  assert.equal(await page.evaluate(() => pilot.count), 22);
  for (const camera of ['front', 'oblique', 'side']) {
    await page.evaluate(v => pilot.setCamera(v), camera); await saveCanvas(`observed-canvas-${camera}`);
  }
  await page.locator('#mode').selectOption('update'); await page.waitForFunction(() => pilot.mode === 'update');
  assert.equal(await page.evaluate(() => pilot.count), 22);
  assert.equal(await page.locator('#seed').count(), 0);
  await page.locator('#mode').selectOption('native'); await page.waitForFunction(() => pilot.mode === 'native');
  assert.deepEqual(await page.evaluate(() => pilot.particleSnapshot), original);
  checks.push('all three modes switch and retain independent configuration');
  assert.deepEqual(errors, []);
  assert.ok(requests.every(r => r.method === 'GET' && r.url.startsWith('http://127.0.0.1:5197/')));
  const stats = await page.evaluate(() => ({ count: pilot.count, drawCalls: pilot.drawCalls, textures: pilot.textures }));
  await page.evaluate(() => pilot.dispose());
  assert.deepEqual(await page.evaluate(() => pilot.resourcesAfterDispose), { geometries: 0, textures: 0 });
  const result = { checks, errors, nativeOnlyRequests, allRequestsLocalGetOnly: true, stats, resourcesAfterDispose: { geometries: 0, textures: 0 } };
  await fs.writeFile(new URL('browser.json', out), JSON.stringify(result, null, 2)+'\n');
  console.log(JSON.stringify({ checks: checks.length, errors, nativeOnlyRequests: nativeOnlyRequests.length, stats }));
} finally { await browser.close(); }
